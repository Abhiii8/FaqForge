import os
from flask import Blueprint, jsonify, current_app, send_file
from docx import Document as DocxDocument
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet
from backend.models.database import Document, FAQ

export_bp = Blueprint('export', __name__)

@export_bp.route('/<int:doc_id>/txt', methods=['GET'])
def export_txt(doc_id):
    doc = Document.query.get_or_404(doc_id)
    faqs = FAQ.query.filter_by(document_id=doc_id).all()
    
    filename = f"faq_export_{doc_id}.txt"
    filepath = os.path.join(current_app.config['EXPORT_FOLDER'], filename)
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(f"FAQs for {doc.filename}\n")
        f.write(f"Generated by FAQForge Offline AI\n")
        f.write("=" * 60 + "\n\n")
        for i, faq in enumerate(faqs, 1):
            status = f"[{faq.verification_status.upper()}]" if faq.verification_status else "[VERIFIED]"
            pages = f"Page(s): {faq.source_pages}" if faq.source_pages else ""
            category = f"Category: {faq.category}" if faq.category else ""
            meta_str = " | ".join(filter(None, [status, category, pages]))
            
            f.write(f"Q{i}: {faq.question}\n")
            if meta_str:
                f.write(f"({meta_str})\n")
            f.write(f"A{i}: {faq.answer}\n\n")
            
    return send_file(filepath, as_attachment=True)

@export_bp.route('/<int:doc_id>/docx', methods=['GET'])
def export_docx(doc_id):
    doc = Document.query.get_or_404(doc_id)
    faqs = FAQ.query.filter_by(document_id=doc_id).all()
    
    filename = f"faq_export_{doc_id}.docx"
    filepath = os.path.join(current_app.config['EXPORT_FOLDER'], filename)
    
    docx = DocxDocument()
    docx.add_heading(f"FAQs for {doc.filename}", 0)
    
    for i, faq in enumerate(faqs, 1):
        docx.add_heading(f"Q{i}: {faq.question}", level=1)
        meta_items = []
        if faq.verification_status:
            meta_items.append(f"Status: {faq.verification_status.title()}")
        if faq.category:
            meta_items.append(f"Category: {faq.category}")
        if faq.source_pages:
            meta_items.append(f"Page: {faq.source_pages}")
        if meta_items:
            docx.add_paragraph(" | ".join(meta_items))
        docx.add_paragraph(faq.answer)
        docx.add_paragraph("")
        
    docx.save(filepath)
    return send_file(filepath, as_attachment=True)

@export_bp.route('/<int:doc_id>/pdf', methods=['GET'])
def export_pdf(doc_id):
    doc = Document.query.get_or_404(doc_id)
    faqs = FAQ.query.filter_by(document_id=doc_id).all()
    
    filename = f"faq_export_{doc_id}.pdf"
    filepath = os.path.join(current_app.config['EXPORT_FOLDER'], filename)
    
    pdf = SimpleDocTemplate(filepath, pagesize=letter)
    styles = getSampleStyleSheet()
    story = []
    
    title = Paragraph(f"<b>FAQs for {doc.filename}</b>", styles['Title'])
    story.append(title)
    story.append(Spacer(1, 14))
    
    for i, faq in enumerate(faqs, 1):
        q = Paragraph(f"<b>Q{i}: {faq.question}</b>", styles['Heading2'])
        meta_parts = []
        if faq.verification_status:
            meta_parts.append(f"<b>Status:</b> {faq.verification_status.title()}")
        if faq.category:
            meta_parts.append(f"<b>Category:</b> {faq.category}")
        if faq.source_pages:
            meta_parts.append(f"<b>Page:</b> {faq.source_pages}")
        meta_p = Paragraph(f"<font color='#666666' size='9'>{' &bull; '.join(meta_parts)}</font>", styles['Normal'])
        a = Paragraph(faq.answer, styles['Normal'])
        
        story.append(q)
        if meta_parts:
            story.append(meta_p)
            story.append(Spacer(1, 4))
        story.append(a)
        story.append(Spacer(1, 14))
        
    pdf.build(story)
    return send_file(filepath, as_attachment=True)
